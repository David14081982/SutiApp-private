'use strict';
// Server-only template packaging. Never writes the source workbook.
const fs = require('fs');
const path = require('path');
const os = require('os');
const crypto = require('crypto');
const { spawnSync } = require('child_process');
const JSZip = require('../app/vendor/jszip-3.10.1/jszip.min.js');
const EXPECTED_SHA = 'da8c9785b4f4a62bc087403a06492766cf8dae59e2d239589396a31f842e32eb';
const filename = 'Reporte mensuales secretaría de finanzas.xlsx';

function assertPrivateTarget(root, target) {
  const relative = path.relative(root, target).split(path.sep).join('/');
  const git = args => spawnSync('git', args, { cwd: root, encoding: 'utf8', windowsHide: true });
  const tracked = git(['ls-files', '--', relative]);
  if (tracked.error || tracked.status !== 0) throw new Error('PRIVATE_TEMPLATE_GIT_CHECK_FAILED');
  if (tracked.stdout.trim()) throw new Error('PRIVATE_TEMPLATE_TRACKED');
  const ignored = git(['check-ignore', '--quiet', '--', relative]);
  if (ignored.error || ignored.status !== 0) throw new Error('PRIVATE_TEMPLATE_NOT_IGNORED');
}

async function main() {
  const root = path.resolve(__dirname, '..');
  const target = path.join(root, 'supabase/functions/reports-jc/template.mjs');
  assertPrivateTarget(root, target);
  const source = process.argv[2] || path.join(os.homedir(), 'Downloads', filename);
  const bytes = fs.readFileSync(source);
  const sha = crypto.createHash('sha256').update(bytes).digest('hex');
  if (sha !== EXPECTED_SHA) throw new Error('Original template changed; audit the replacement before packaging.');
  const zip = await JSZip.loadAsync(bytes, { checkCRC32: true });
  const workbook = await zip.file('xl/workbook.xml').async('string');
  if ((workbook.match(/<sheet\s/g) || []).length !== 17) throw new Error('Expected exactly 17 template sheets.');
  assertPrivateTarget(root, target);
  fs.mkdirSync(path.dirname(target), { recursive: true });
  const content = '// PRIVATE server-only template. Do not include in public assets or frontend bundles.\n'
    + '// Generated by scripts/build-reports-jc-template.js; original XLSX is read-only.\n'
    + 'export const TEMPLATE_SHA256 = ' + JSON.stringify(sha) + ';\n'
    + 'export const TEMPLATE_FILENAME = ' + JSON.stringify(filename) + ';\n'
    + 'export const TEMPLATE_BASE64 = ' + JSON.stringify(bytes.toString('base64')) + ';\n';
  fs.writeFileSync(target, content, 'utf8');
  if (crypto.createHash('sha256').update(fs.readFileSync(source)).digest('hex') !== sha) throw new Error('Source changed during packaging.');
  console.log(JSON.stringify({ status: 'PASS', bytes: bytes.length, sheets: 17, sha256: sha, output: 'supabase/functions/reports-jc/template.mjs' }));
}
if (require.main === module) main().catch(error => { console.error(error.message); process.exitCode = 1; });
module.exports = { assertPrivateTarget };
