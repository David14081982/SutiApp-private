'use strict';
// Generate the browser worker from the exact, credential-free server modules.
const fs=require('fs'),path=require('path'),vm=require('vm'),crypto=require('crypto');
const root=path.resolve(__dirname,'..'),base=path.join(root,'supabase/functions/sicof');
const engine=fs.readFileSync(path.join(base,'engine.mjs'),'utf8').replace(/\r\n/g,'\n');
const simulation=fs.readFileSync(path.join(base,'simulation.mjs'),'utf8').replace(/\r\n/g,'\n');
const names=source=>[...source.matchAll(/^export (?:async )?(?:function|const) ([A-Za-z0-9_]+)/gm)].map(match=>match[1]);
const unexport=source=>source.replace(/^export /gm,'');
const imports=[...simulation.matchAll(/^import\s+\{([^}]+)\}\s+from\s+['"]([^'"]+)['"];?\s*$/gm)];
if(imports.some(match=>match[2]!=='./engine.mjs'))throw Error('SICOF_WORKER_IMPORT_NOT_ALLOWED');
let body=simulation;for(const match of imports)body=body.replace(match[0],'const {'+match[1]+'} = engine;');
if(/^import /m.test(body))throw Error('SICOF_WORKER_UNEXPECTED_IMPORT');
const hash=source=>crypto.createHash('sha256').update(source).digest('hex');
const code=`/* GENERATED by scripts/build-sicof-simulation-worker.js
engine sha256 ${hash(engine)}
simulation sha256 ${hash(simulation)}
No credentials, financial storage, network calls or transaction writers. */
'use strict';
const engine=(()=>{${unexport(engine)}\nreturn {${names(engine).join(',')}};})();
const simulation=(()=>{${unexport(body)}\nreturn {${names(simulation).join(',')}};})();
let seed=null,workspace=null,paymentIndex=null;
self.onmessage=async event=>{
 const {id,type}=event.data||{};
 try{
  if(type==='INIT'){
   seed=event.data.seed;workspace=event.data.workspace;
   if(seed?.version!=='SICOF_SIMULATION_INPUT_V1'||!workspace)throw Error('SICOF_SIMULATION_INPUT_INVALID');
   paymentIndex=new Map(workspace.payments.map((payment,index)=>[payment,index]));
   self.postMessage({id,data:{ready:true}});return;
  }
  if(type!=='CALCULATE'||!seed)throw Error('SICOF_SIMULATION_INPUT_REQUIRED');
  const start=performance.now(),value=await simulation.executeSimulation(seed,workspace,event.data.input);
  const {loans,payments,funds,paymentMetrics}=value.workspace;
  // Transport only changed selectors, not thousands of unchanged loan fields.
  const selection={payments:payments.map(payment=>paymentIndex.get(payment)),loanPeriods:loans.map(loan=>loan.schedule.map(payment=>payment.in_period))};
  const loanIndex=new Map(loans.map((loan,index)=>[loan,index]));
  const result={...value.result,rows:value.result.rows.map(({loans:personLoans,...row})=>({...row,loan_indexes:personLoans.map(loan=>loanIndex.get(loan))}))};
  self.postMessage({id,data:{result,selection,funds,paymentMetrics,basis:value.basis,elapsed_ms:performance.now()-start}});
 }catch(error){self.postMessage({id,error:/^SICOF_[A-Z_]+$/.test(error?.message||'')?error.message:'SICOF_SIMULATION_FAILED'});}
};
`;
if(/\b(?:fetch|XMLHttpRequest|importScripts|localStorage|indexedDB)\s*\(/.test(code))throw Error('SICOF_WORKER_EXTERNAL_DEPENDENCY');
new vm.Script(code);
const file=path.join(root,'app/sicof-simulation-worker.js');
if(process.argv.includes('--check')){if(fs.readFileSync(file,'utf8')!==code)throw Error('SICOF_WORKER_STALE');}
else fs.writeFileSync(file,code);
console.log(JSON.stringify({status:'PASS',engineSha256:hash(engine),simulationSha256:hash(simulation),workerSha256:hash(code),bytes:Buffer.byteLength(code)}));
