const assert = require('assert');
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8');
const source = JSON.parse(read('data/program-catalog-source.json'));

assert.strictEqual(source.items.length, 134);
assert.deepStrictEqual(source.counts, {aires:16,auto:3,casa:35,computo:1,donativos:1,farma:50,puertas:3,renta:1,solar:4,terrenos:3,tours:17});
assert(/^[A-F0-9]{64}$/.test(source.source_snapshot_hash));
assert.strictEqual(new Set(source.items.map((row)=>row.id)).size, 134);
assert.strictEqual(new Set(source.items.map((row)=>`${row.source_sheet}:${row.source_row_ordinal}`)).size, 134);
const farma = source.items.filter((row)=>row.program_key==='farma');
assert.strictEqual(farma.length, 50);
assert(farma.every((row)=>row.request_mode==='supabase'&&!row.legacy_boundary));
assert(farma.some((row)=>row.name==='ACIDO ACETILSALICILICO'&&row.quantity_raw==='8 CAJAS'&&row.presentation_raw==='300 mg'&&row.category_raw==='Medicamento Gratis'&&row.assets.length===1));
assert(source.items.filter((row)=>row.program_key!=='farma').every((row)=>row.request_mode==='legacy_pending'));
assert.strictEqual(source.items.filter((row)=>row.price_cash!==null).length, 65);
assert(source.items.some((row)=>row.program_key==='casa'&&row.source_row_ordinal===2&&row.price_cash===1600000&&row.source_payload.Precio==='$1,600,000'));

const migration = read('supabase/migrations/20260822000100_create_program_catalog_cutover.sql');
const favoritesMigration = read('supabase/migrations/20260822000101_add_program_catalog_favorites.sql');
assert(migration.includes('force row level security'));
assert(migration.includes("request_mode='supabase'"));
assert(migration.includes('source_payload jsonb'));
assert(!/grant select[^;]*source_payload/i.test(migration));
assert(migration.includes('program_catalog_linked_private_storage_read'));
assert(migration.includes('a.storage_path=storage.objects.name'));
assert(migration.includes('actor_real_auth_user_id'));
assert(migration.includes('public.get_effective_affiliate_id()'));
assert(favoritesMigration.includes('force row level security') && favoritesMigration.includes('auth_user_id=(select auth.uid())'));

const repository = read('app/program-catalog-repository.js');
const store = read('app/catalog-store.jsx');
const finance = read('app/fincat-store.jsx');
const product = read('app/screens-marketplace.jsx');
const detail = read('app/screens-catalogo.jsx');
